/**
 * 图表数据配置常量
 *
 * 动态冗余数据加载策略：
 * - 根据启用的指标计算所需的最大历史数据量
 * - 实际加载量 = 显示数据量 + (指标最大需求 * 2)
 * - 例如：显示 50 根 + MACD 需要 35 根 * 2 = 120 根
 */
export const CHART_DATA_CONFIG = {
  /**
   * 显示数据量：初始图表显示的 K 线数量
   * - 用户看到的 K 线数量
   * - 保持 50 根以获得良好的视觉体验
   */
  DISPLAY_DATA_SIZE: 50,

  /**
   * 历史加载量：每次向左滚动加载的数据量
   * - 保持与显示数据量一致，便于计算
   */
  HISTORY_LOAD_SIZE: 50,

  /**
   * 最大数据缓存：防止内存溢出
   * - 当数据超过此值时，裁剪旧数据
   */
  MAX_DATA_SIZE: 300,

  /**
   * 基础数据量：未启用任何指标时的默认加载量
   * - 确保即使没有指标也有足够的数据
   */
  BASE_DATA_SIZE: 100,
} as const;
